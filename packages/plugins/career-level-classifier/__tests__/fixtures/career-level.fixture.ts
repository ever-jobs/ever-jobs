import type { CareerLevel, CareerLevelInput } from '@ever-jobs/models';

/**
 * Labelled evaluation fixture for the career-level classifier (Spec 1730, FR-11).
 *
 * Labelling policy — the label is what the posting *explicitly states*, read by a careful human:
 *
 * - An explicit level word wins (intern, new grad, junior, II, senior, staff, principal, manager,
 *   director, VP …). Seniority implied only by the occupation (Barista, Warehouse Associate,
 *   Registered Nurse) is `unknown`.
 * - Product / program / project / account-type "manager" titles are individual-contributor roles:
 *   `unknown` unless another modifier states a level (Q-105).
 * - A title that *administers* an early-career programme (Internship Coordinator, Campus
 *   Recruiter) is not itself an internship or new-grad role.
 * - Decisions recorded in Q-105: apprenticeship → entry; graduate research/teaching assistant →
 *   internship; bank "VP" + IC role → senior; distinguished / technical fellow → principal;
 *   Engineer III → senior; school principal → director; chief of staff → director.
 *
 * Titles are realistic postings of the kind the aggregator ingests (ATS boards, company pages,
 * job boards, several languages). Keep the list append-only; if a label is wrong, fix the label
 * in its own commit with the reason.
 */
export interface CareerLevelCase {
  /** Classifier input (title plus, for a few cases, structured fields or a description). */
  input: CareerLevelInput;
  /** Gold label. */
  expected: CareerLevel;
  /** Why this case is here (tricky negatives, decisions …). */
  note?: string;
}

const t = (title: string, expected: CareerLevel, note?: string): CareerLevelCase => ({
  input: { title },
  expected,
  note,
});

